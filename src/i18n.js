const DYNAMIC_PATTERNS = [
  [/^任务结束：(.*)$/, 'Task ended: {value}'],
  [/^已提交：(.*)$/, 'Submitted: {value}'],
  [/^轮询中：(.*)$/, 'Polling: {value}'],
  [/^历史记录：(.*)$/, 'History: {value}'],
  [/^已保存模板：(.*)$/, 'Template saved: {value}'],
  [/^已加载模板：(.*)$/, 'Template loaded: {value}'],
  [/^已删除模板：(.*)$/, 'Template deleted: {value}'],
  [/^视频下载失败：(.*)$/, 'Video download failed: {value}'],
  [/^轮询已达上限（(\d+) 次），请手动刷新$/, 'Polling limit reached ({value}); refresh manually.'],
  [/^([\d.]+) 分钟$/, '{value} min'],
];

export function normalizeLanguage(value) {
  return value === 'en' ? 'en' : DEFAULT_LANGUAGE;
}

export function translate(language, source, params = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  const template = normalizedLanguage === 'en' ? (EN_MESSAGES[source] || source) : source;
  return Object.entries(params).reduce((message, [key, value]) => {
    return message.replaceAll(`{${key}}`, String(value));
  }, template);
}

export function translateDynamic(language, source) {
  const text = String(source || '');
  const translated = translate(language, text);
  if (language !== 'en' || translated !== text) {
    return translated;
  }
  for (const [pattern, template] of DYNAMIC_PATTERNS) {
    const match = text.match(pattern);
    if (match) {
      return template.replace('{value}', translate(language, match[1]));
    }
  }
  return text;
}
